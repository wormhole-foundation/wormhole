// AddRegular adds an account-based post_message.
func (b *Builder) AddRegular(spec RegularSpec) *Builder {
	msgKey := genKey(messageTag, b.msgCounter)
	if spec.MessageAccountKey != nil {
		msgKey = *spec.MessageAccountKey
	}
	b.msgCounter++
	msgIdx := b.ensureKey(msgKey)
	b.msgKeys = append(b.msgKeys, msgKey)

	n := spec.NumAccounts
	if n < postMessageMinNumAccounts {
		n = postMessageMinNumAccounts
	}
	progIdx := b.coreIndex()
	if spec.WrongCoreProgram {
		progIdx = b.wrongProgramIndex()
	}
	inst := solana.CompiledInstruction{
		ProgramIDIndex: progIdx,
		Accounts:       b.accountRefs(n, msgIdx),
		Data:           solana.Base58(b.regularInstrData(spec.Kind, spec.Msg)),
	}
	if spec.Location == Outer {
		b.topLevel = append(b.topLevel, inst)
	} else {
		wrapperIdx := b.addWrapperTopLevel()
		b.addInnerSet(wrapperIdx, []solana.CompiledInstruction{inst})
	}

	owner := b.cfg.Contract
	if spec.Account.Owner != nil {
		owner = *spec.Account.Owner
	}
	blob := b.accountBlob(spec.Kind, spec.Msg, spec.Account)
	b.accounts = append(b.accounts, AccountInfoResponse{
		Pubkey:   msgKey,
		Owner:    owner,
		Lamports: 1,
		Data:     blob,
	})
	return b
}

// AddShim adds a shim publication (shim post_message + core post_message + shim MessageEvent).
func (b *Builder) AddShim(spec ShimSpec) *Builder {
	if !b.shimEnabled {
		b.fail(fmt.Errorf("AddShim requires Config.ShimContract to be set"))
		return b
	}
	ordering := spec.Ordering
	if ordering == nil {
		ordering = DefaultShimOrder
	}

	build := func(p ShimPart) solana.CompiledInstruction {
		var progIdx uint16
		var data []byte
		switch p {
		case ShimPostPart:
			progIdx, data = b.shimIndex(), b.shimPostData(spec.Msg)
		case CorePostPart:
			progIdx, data = b.coreIndex(), b.shimCoreData(spec.Msg)
		default: // ShimEventPart
			progIdx, data = b.shimIndex(), b.shimEventData(spec.Msg)
		}
		// Redirect this part to a wrong program to exercise the core-bridge
		// (CorePostPart) or shim-contract (ShimEventPart) program check.
		if spec.WrongProgramPart != nil && *spec.WrongProgramPart == p {
			progIdx = b.wrongProgramIndex()
		}
		return solana.CompiledInstruction{ProgramIDIndex: progIdx, Data: solana.Base58(data)}
	}

	if spec.Topology == Direct {
		// Shim post_message is top-level; the remaining parts form the matching inner set.
		b.topLevel = append(b.topLevel, build(ShimPostPart))
		topIdx := uint16(len(b.topLevel) - 1) // #nosec G115
		var innerParts []solana.CompiledInstruction
		for _, p := range ordering {
			if p == ShimPostPart {
				continue // the post is the top-level instruction in the direct case
			}
			innerParts = append(innerParts, build(p))
		}
		b.addInnerSet(topIdx, innerParts)
	} else {
		// Integrator: all parts live in a single inner set behind a wrapper program.
		wrapperIdx := b.addWrapperTopLevel()
		var innerParts []solana.CompiledInstruction
		for _, p := range ordering {
			innerParts = append(innerParts, build(p))
		}
		b.addInnerSet(wrapperIdx, innerParts)
	}
	return b
}

// AddClose adds a close_posted_message event. It forces the transaction's
// reobservation flag to true (close events are processed only during reobservation).
func (b *Builder) AddClose(spec CloseSpec) *Builder {
	b.reobs = true

	msgKey := genKey(messageTag, b.msgCounter)
	if spec.MessageAccountKey != nil {
		msgKey = *spec.MessageAccountKey
	}
	b.msgCounter++
	msgIdx := b.ensureKey(msgKey)
	b.msgKeys = append(b.msgKeys, msgKey)

	n := spec.NumAccounts
	if n < closeMinNumAccounts {
		n = closeMinNumAccounts
	}
	closeInst := solana.CompiledInstruction{
		ProgramIDIndex: b.coreIndex(),
		Accounts:       b.accountRefs(n, msgIdx),
		Data:           solana.Base58{closePostedMessageInstructionID},
	}
	// The close event data carries msu-prefixed content in practice, but the prefix
	// is caller-controllable via AccountContent. Default to reliable "msg".
	eventProgIdx := b.coreIndex()
	if spec.WrongCoreProgram {
		eventProgIdx = b.wrongProgramIndex()
	}
	eventInst := solana.CompiledInstruction{
		ProgramIDIndex: eventProgIdx,
		Data:           solana.Base58(b.closeEventData(PostMessage, spec.Msg, spec.Account)),
	}

	if spec.Location == Outer {
		// Top-level close instruction; the CPI event is in the matching inner set.
		b.topLevel = append(b.topLevel, closeInst)
		topIdx := uint16(len(b.topLevel) - 1) // #nosec G115
		b.addInnerSet(topIdx, []solana.CompiledInstruction{eventInst})
	} else {
		// close_posted_message called via CPI: close instruction and its event are
		// sibling inner instructions behind a wrapper program.
		wrapperIdx := b.addWrapperTopLevel()
		b.addInnerSet(wrapperIdx, []solana.CompiledInstruction{closeInst, eventInst})
	}
	return b
}

// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------

// Build assembles the accumulated instructions and accounts into a Bundle. It
// returns an error if any encoding step failed.
func (b *Builder) Build() (*Bundle, error) {
	if b.err != nil {
		return nil, b.err
	}

	// Deterministic non-zero signature (used by the watcher as the TxID).
	var sig solana.Signature
	for i := range sig {
		sig[i] = 0x11
	}

	tx := &solana.Transaction{
		Message: solana.Message{
			AccountKeys:     b.keys,
			Header:          solana.MessageHeader{NumRequiredSignatures: 1, NumReadonlySignedAccounts: 0, NumReadonlyUnsignedAccounts: 1},
			RecentBlockhash: b.cfg.RecentBlockhash,
			Instructions:    b.topLevel,
		},
		Signatures: []solana.Signature{sig},
	}
	meta := &rpc.TransactionMeta{
		InnerInstructions: b.inner,
	}
	if b.cfg.TxFailed {
		// A representative on-chain failure. Any non-nil Err makes
		// validateTransactionMeta reject the transaction; the shape mirrors what the
		// RPC returns for a failed instruction.
		meta.Err = map[string]interface{}{
			"InstructionError": []interface{}{0, map[string]interface{}{"Custom": 1}},
		}
	}

	if len(b.cfg.LookupTables) > 0 {
		b.applyLookupTable(tx, meta)
		if b.err != nil {
			return nil, b.err
		}
	}

	name := b.cfg.Name
	if name == "" {
		name = "bundle"
	}
	return &Bundle{
		Name:            name,
		IsReobservation: b.reobs,
		Slot:            b.cfg.Slot,
		Contract:        b.cfg.Contract,
		ShimContract:    b.cfg.ShimContract,
		Transaction:     tx,
		Meta:            meta,
		Accounts:        b.accounts,
	}, nil
}

// applyLookupTable rewrites the assembled (legacy) transaction into a versioned (v0) one
// that reaches its referenced non-program accounts through one or more Address Lookup
// Tables (Config.LookupTables). Invoked programs and the index-0 fee-payer signer stay
// static (v0 forbids them in a lookup). The referenced movable accounts — the message
// account(s) plus the emitter/sequence/payer-style fillers accountRefs added — are
// distributed across the tables' writable/readonly sections per the specs, and every
// instruction index is rewritten to the composite ordering the runtime (and the watcher's
// ResolveLookups) uses: static keys, then all writable-loaded across tables (in table
// order), then all readonly-loaded across tables. One ALT account per table is synthesized
// into Accounts so the watcher fetches, verifies, and decodes each.
func (b *Builder) applyLookupTable(tx *solana.Transaction, meta *rpc.TransactionMeta) {
	specs := b.cfg.LookupTables

	// 1. Mark keys that must remain static: index-0 signer + every invoked program (plus
	//    the core/shim contracts, which are programs even if this bundle never invokes them).
	isStatic := make([]bool, len(b.keys))
	if len(isStatic) > 0 {
		isStatic[0] = true
	}
	markPrograms := func(insts []solana.CompiledInstruction) {
		for _, in := range insts {
			isStatic[in.ProgramIDIndex] = true
		}
	}
	markPrograms(b.topLevel)
	for _, set := range b.inner {
		markPrograms(set.Instructions)
	}
	isStatic[b.keyIndex[b.cfg.Contract]] = true
	if b.shimEnabled {
		isStatic[b.keyIndex[b.cfg.ShimContract]] = true
	}

	isMsg := make(map[solana.PublicKey]bool, len(b.msgKeys))
	for _, k := range b.msgKeys {
		isMsg[k] = true
	}

	// 2. Static keys keep dense low indices; collect movable message accounts and fillers.
	newIndex := make([]uint16, len(b.keys))
	var staticKeys, msgAccts, fillers []solana.PublicKey
	for old, k := range b.keys {
		switch {
		case isStatic[old]:
			newIndex[old] = uint16(len(staticKeys)) // #nosec G115
			staticKeys = append(staticKeys, k)
		case isMsg[k]:
			msgAccts = append(msgAccts, k)
		default:
			fillers = append(fillers, k)
		}
	}

	// 3. Validate the specs against the referenced movable accounts.
	totalSlots := 0
	for _, s := range specs {
		totalSlots += s.Writable + s.Readonly
	}
	movable := len(msgAccts) + len(fillers)
	if totalSlots != movable {
		b.fail(fmt.Errorf("lookup table slots (%d) != referenced movable accounts (%d); adjust LookupTables or NumAccounts", totalSlots, movable))
		return
	}
	mt := b.cfg.LookupMessageTable
	if mt < 0 || mt >= len(specs) {
		b.fail(fmt.Errorf("LookupMessageTable %d out of range for %d tables", mt, len(specs)))
		return
	}
	msgCap := specs[mt].Writable
	if b.cfg.LookupMessageReadonly {
		msgCap = specs[mt].Readonly
	}
	if len(msgAccts) > msgCap {
		b.fail(fmt.Errorf("message account(s) (%d) exceed table %d's %s capacity (%d)", len(msgAccts), mt, sectionName(b.cfg.LookupMessageReadonly), msgCap))
		return
	}

	// 4. Fill each table's writable/readonly slots: message accounts into their placement
	//    first, then fillers everywhere else in (table, section) order.
	tW := make([][]solana.PublicKey, len(specs))
	tR := make([][]solana.PublicKey, len(specs))
	if b.cfg.LookupMessageReadonly {
		tR[mt] = append(tR[mt], msgAccts...)
	} else {
		tW[mt] = append(tW[mt], msgAccts...)
	}
	fi := 0
	for t := range specs {
		for len(tW[t]) < specs[t].Writable {
			tW[t] = append(tW[t], fillers[fi])
			fi++
		}
		for len(tR[t]) < specs[t].Readonly {
			tR[t] = append(tR[t], fillers[fi])
			fi++
		}
	}

	// 5. Composite indices (two-phase, matching GetAddressTableLookupAccounts): every
	//    writable slot across all tables in table order, then every readonly slot.
	base := len(staticKeys)
	var loadedWritable, loadedReadonly []solana.PublicKey
	assign := func(k solana.PublicKey, idx int) {
		newIndex[b.keyIndex[k]] = uint16(idx) // #nosec G115 -- generated inputs are tiny
	}
	for t := range specs {
		for _, k := range tW[t] {
			assign(k, base+len(loadedWritable))
			loadedWritable = append(loadedWritable, k)
		}
	}
	roBase := base + len(loadedWritable)
	for t := range specs {
		for _, k := range tR[t] {
			assign(k, roBase+len(loadedReadonly))
			loadedReadonly = append(loadedReadonly, k)
		}
	}

	// 6. Rewrite every instruction's program and account indices through the remap.
	remap := func(insts []solana.CompiledInstruction) {
		for i := range insts {
			insts[i].ProgramIDIndex = newIndex[insts[i].ProgramIDIndex]
			for j := range insts[i].Accounts {
				insts[i].Accounts[j] = newIndex[insts[i].Accounts[j]]
			}
		}
	}
	remap(tx.Message.Instructions) // shares backing array with b.topLevel
	for i := range meta.InnerInstructions {
		remap(meta.InnerInstructions[i].Instructions)
	}

	// 7. Emit one lookup + one synthesized ALT account per table. Each table's Addresses
	//    are writable-then-readonly, so its indexes are the leading/trailing positions.
	lookups := make([]solana.MessageAddressTableLookup, 0, len(specs))
	for t := range specs {
		addrs := append(append([]solana.PublicKey{}, tW[t]...), tR[t]...)
		writableIdx := make(solana.Uint8SliceAsNum, len(tW[t]))
		for i := range tW[t] {
			writableIdx[i] = uint8(i) // #nosec G115 -- ALT holds at most 256 addresses
		}
		readonlyIdx := make(solana.Uint8SliceAsNum, len(tR[t]))
		for i := range tR[t] {
			readonlyIdx[i] = uint8(len(tW[t]) + i) // #nosec G115
		}
		altKey := genKey(lookupTableTag, t)
		lookups = append(lookups, solana.MessageAddressTableLookup{
			AccountKey:      altKey,
			WritableIndexes: writableIdx,
			ReadonlyIndexes: readonlyIdx,
		})

		state := lookup.AddressLookupTableState{
			TypeIndex:        1, // LookupTable (0 = uninitialized)
			DeactivationSlot: math.MaxUint64,
			LastExtendedSlot: b.cfg.Slot,
			Addresses:        solana.PublicKeySlice(addrs),
		}
		var buf bytes.Buffer
		if err := state.MarshalWithEncoder(bin.NewBinEncoder(&buf)); err != nil {
			b.fail(fmt.Errorf("encode lookup table %d state: %w", t, err))
			return
		}
		b.accounts = append(b.accounts, AccountInfoResponse{
			Pubkey:   altKey,
			Owner:    addressLookupTableProgramID,
			Lamports: 1,
			Data:     buf.Bytes(),
		})
	}

	tx.Message.AccountKeys = staticKeys
	tx.Message.SetAddressTableLookups(lookups)
	meta.LoadedAddresses = rpc.LoadedAddresses{
		Writable: solana.PublicKeySlice(loadedWritable),
		ReadOnly: solana.PublicKeySlice(loadedReadonly),
	}
}

func sectionName(readonly bool) string {
	if readonly {
		return "readonly"
	}
	return "writable"
}
