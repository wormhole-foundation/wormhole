// AccountInfoResponse is one getAccountInfo result. It marshals to the RPC "value"
// shape (data as ["<base64>","base64"]) so a consumer can map pubkey -> value into
// a mock directly.
type AccountInfoResponse struct {
	Pubkey     solana.PublicKey
	Owner      solana.PublicKey
	Lamports   uint64
	Data       []byte
	Executable bool
	RentEpoch  uint64
}

// MarshalJSON emits the RPC getAccountInfo value shape plus the pubkey.
func (a AccountInfoResponse) MarshalJSON() ([]byte, error) {
	return json.Marshal(map[string]interface{}{
		"pubkey":     a.Pubkey,
		"owner":      a.Owner,
		"lamports":   a.Lamports,
		"data":       []interface{}{base64.StdEncoding.EncodeToString(a.Data), "base64"},
		"executable": a.Executable,
		"rentEpoch":  a.RentEpoch,
	})
}

// Bundle is the generated set of inputs for a single processTransaction call.
// Transaction and Meta marshal to the native solana-go JSON shapes and round-trip
// back via json.Unmarshal.
type Bundle struct {
	Name            string                `json:"name"`
	IsReobservation bool                  `json:"isReobservation"`
	Slot            uint64                `json:"slot"`
	Contract        solana.PublicKey      `json:"contract"`
	ShimContract    solana.PublicKey      `json:"shimContract"`
	Transaction     *solana.Transaction   `json:"transaction"`
	Meta            *rpc.TransactionMeta  `json:"meta"`
	Accounts        []AccountInfoResponse `json:"accounts"`
}

